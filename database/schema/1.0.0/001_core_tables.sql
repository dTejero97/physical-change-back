-- Physical Change 1.0.0 - ESQUEMA (inmutable). Núcleo: usuarios, ejercicios, entrenamientos, asignaciones.
CREATE TABLE APP_USER (
  ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMAIL         VARCHAR2(160) NOT NULL,
  PASSWORD_HASH VARCHAR2(100) NOT NULL,
  FULL_NAME     VARCHAR2(120) NOT NULL,
  ROLE          VARCHAR2(20)  NOT NULL,
  TRAINER_ID    NUMBER,
  ACTIVE        NUMBER(1) DEFAULT 1 NOT NULL,
  CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_APP_USER_EMAIL UNIQUE (EMAIL),
  CONSTRAINT CK_APP_USER_ROLE CHECK (ROLE IN ('ADMIN','TRAINER','CLIENT')),
  CONSTRAINT FK_APP_USER_TRAINER FOREIGN KEY (TRAINER_ID) REFERENCES APP_USER (ID)
);
CREATE INDEX IX_APP_USER_TRAINER ON APP_USER (TRAINER_ID);

CREATE TABLE EXERCISE (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME         VARCHAR2(120) NOT NULL,
  MUSCLE_GROUP VARCHAR2(60),
  DESCRIPTION  VARCHAR2(2000),
  OWNER_ID     NUMBER,
  CONSTRAINT FK_EXERCISE_OWNER FOREIGN KEY (OWNER_ID) REFERENCES APP_USER (ID)
);

CREATE TABLE WORKOUT (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TRAINER_ID NUMBER NOT NULL,
  NAME       VARCHAR2(120) NOT NULL,
  NOTES      VARCHAR2(2000),
  CONSTRAINT FK_WORKOUT_TRAINER FOREIGN KEY (TRAINER_ID) REFERENCES APP_USER (ID)
);

CREATE TABLE WORKOUT_EXERCISE (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  WORKOUT_ID  NUMBER NOT NULL,
  EXERCISE_ID NUMBER NOT NULL,
  POSITION    NUMBER(3) NOT NULL,
  SETS        NUMBER(3),
  REPS        NUMBER(4),
  REST_SEC    NUMBER(4),
  CONSTRAINT FK_WE_WORKOUT  FOREIGN KEY (WORKOUT_ID)  REFERENCES WORKOUT (ID),
  CONSTRAINT FK_WE_EXERCISE FOREIGN KEY (EXERCISE_ID) REFERENCES EXERCISE (ID)
);

CREATE TABLE WORKOUT_ASSIGNMENT (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  WORKOUT_ID     NUMBER NOT NULL,
  CLIENT_ID      NUMBER NOT NULL,
  SCHEDULED_DATE DATE NOT NULL,
  COMPLETED_DATE DATE,
  CONSTRAINT FK_WA_WORKOUT FOREIGN KEY (WORKOUT_ID) REFERENCES WORKOUT (ID),
  CONSTRAINT FK_WA_CLIENT  FOREIGN KEY (CLIENT_ID)  REFERENCES APP_USER (ID)
);
CREATE INDEX IX_WA_CLIENT ON WORKOUT_ASSIGNMENT (CLIENT_ID);

CREATE TABLE WEEKLY_PROGRAM (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TRAINER_ID NUMBER NOT NULL,
  NAME       VARCHAR2(120) NOT NULL,
  CONSTRAINT FK_WP_TRAINER FOREIGN KEY (TRAINER_ID) REFERENCES APP_USER (ID)
);
CREATE TABLE WEEKLY_PROGRAM_DAY (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PROGRAM_ID NUMBER NOT NULL,
  DAY_OF_WEEK NUMBER(1) NOT NULL,
  WORKOUT_ID NUMBER NOT NULL,
  CONSTRAINT CK_WPD_DAY CHECK (DAY_OF_WEEK BETWEEN 1 AND 7),
  CONSTRAINT FK_WPD_PROGRAM FOREIGN KEY (PROGRAM_ID) REFERENCES WEEKLY_PROGRAM (ID),
  CONSTRAINT FK_WPD_WORKOUT FOREIGN KEY (WORKOUT_ID) REFERENCES WORKOUT (ID)
);
