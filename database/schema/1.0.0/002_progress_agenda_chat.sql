CREATE TABLE PROGRESS_ENTRY (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CLIENT_ID    NUMBER NOT NULL,
  ENTRY_DATE   DATE NOT NULL,
  WEIGHT_KG    NUMBER(5,2),
  BODY_FAT_PCT NUMBER(4,1),
  NOTES        VARCHAR2(500),
  CONSTRAINT FK_PE_CLIENT FOREIGN KEY (CLIENT_ID) REFERENCES APP_USER (ID)
);
CREATE INDEX IX_PE_CLIENT_DATE ON PROGRESS_ENTRY (CLIENT_ID, ENTRY_DATE);

CREATE TABLE APPOINTMENT (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TRAINER_ID NUMBER NOT NULL,
  CLIENT_ID  NUMBER NOT NULL,
  START_AT   TIMESTAMP NOT NULL,
  END_AT     TIMESTAMP NOT NULL,
  STATUS     VARCHAR2(20) DEFAULT 'BOOKED' NOT NULL,
  TITLE      VARCHAR2(200),
  CONSTRAINT CK_APPT_STATUS CHECK (STATUS IN ('BOOKED','CANCELLED','DONE')),
  CONSTRAINT FK_APPT_TRAINER FOREIGN KEY (TRAINER_ID) REFERENCES APP_USER (ID),
  CONSTRAINT FK_APPT_CLIENT  FOREIGN KEY (CLIENT_ID)  REFERENCES APP_USER (ID)
);
CREATE INDEX IX_APPT_TRAINER_START ON APPOINTMENT (TRAINER_ID, START_AT);

CREATE TABLE CHAT_MESSAGE (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SENDER_ID    NUMBER NOT NULL,
  RECIPIENT_ID NUMBER NOT NULL,
  BODY         VARCHAR2(2000) NOT NULL,
  SENT_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_MSG_SENDER    FOREIGN KEY (SENDER_ID)    REFERENCES APP_USER (ID),
  CONSTRAINT FK_MSG_RECIPIENT FOREIGN KEY (RECIPIENT_ID) REFERENCES APP_USER (ID)
);
CREATE INDEX IX_MSG_PAIR ON CHAT_MESSAGE (SENDER_ID, RECIPIENT_ID, SENT_AT);
