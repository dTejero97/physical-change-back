ALTER TABLE APP_USER ADD (NUTRITION_ENABLED NUMBER(1) DEFAULT 0 NOT NULL);

CREATE TABLE NUTRITION_MEAL (
  ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PLAN_ID   NUMBER NOT NULL,
  MEAL_NAME VARCHAR2(60) NOT NULL,
  POSITION  NUMBER(2) NOT NULL,
  FOOD_ID   NUMBER NOT NULL,
  GRAMS     NUMBER(6,1) NOT NULL,
  CONSTRAINT FK_NM_PLAN FOREIGN KEY (PLAN_ID) REFERENCES NUTRITION_PLAN (ID),
  CONSTRAINT FK_NM_FOOD FOREIGN KEY (FOOD_ID) REFERENCES FOOD (ID)
);
CREATE INDEX IX_NM_PLAN ON NUTRITION_MEAL (PLAN_ID);
