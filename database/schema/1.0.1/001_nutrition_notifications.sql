-- Physical Change 1.0.1 - ESQUEMA (inmutable). Nutrición y notificaciones.
CREATE TABLE FOOD (
  ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME      VARCHAR2(120) NOT NULL,
  KCAL_100G NUMBER(6,1) NOT NULL,
  PROTEIN_G NUMBER(5,1),
  CARBS_G   NUMBER(5,1),
  FAT_G     NUMBER(5,1)
);
CREATE TABLE NUTRITION_PLAN (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TRAINER_ID NUMBER NOT NULL,
  CLIENT_ID  NUMBER NOT NULL,
  NAME       VARCHAR2(120) NOT NULL,
  DAILY_KCAL NUMBER(5),
  NOTES      VARCHAR2(2000),
  CONSTRAINT FK_NP_TRAINER FOREIGN KEY (TRAINER_ID) REFERENCES APP_USER (ID),
  CONSTRAINT FK_NP_CLIENT  FOREIGN KEY (CLIENT_ID)  REFERENCES APP_USER (ID)
);
CREATE TABLE NOTIFICATION (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ID    NUMBER NOT NULL,
  TITLE      VARCHAR2(160) NOT NULL,
  BODY       VARCHAR2(1000),
  READ_FLAG  NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_NOTIF_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER (ID)
);
