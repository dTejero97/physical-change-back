CREATE TABLE PAYMENT (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CLIENT_ID  NUMBER NOT NULL,
  TRAINER_ID NUMBER NOT NULL,
  AMOUNT     NUMBER(10,2) NOT NULL,
  CURRENCY   VARCHAR2(3) DEFAULT 'EUR' NOT NULL,
  STATUS     VARCHAR2(20) DEFAULT 'PAID' NOT NULL,
  PAID_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_PAY_CLIENT  FOREIGN KEY (CLIENT_ID)  REFERENCES APP_USER (ID),
  CONSTRAINT FK_PAY_TRAINER FOREIGN KEY (TRAINER_ID) REFERENCES APP_USER (ID)
);
CREATE TABLE INVOICE (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PAYMENT_ID NUMBER NOT NULL,
  NUMBER_REF VARCHAR2(30) NOT NULL,
  ISSUED_AT  DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT UQ_INVOICE_NUMBER UNIQUE (NUMBER_REF),
  CONSTRAINT FK_INV_PAYMENT FOREIGN KEY (PAYMENT_ID) REFERENCES PAYMENT (ID)
);
CREATE TABLE ACHIEVEMENT (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODE        VARCHAR2(40) NOT NULL,
  NAME        VARCHAR2(120) NOT NULL,
  DESCRIPTION VARCHAR2(400),
  CONSTRAINT UQ_ACHIEVEMENT_CODE UNIQUE (CODE)
);
CREATE TABLE USER_ACHIEVEMENT (
  USER_ID        NUMBER NOT NULL,
  ACHIEVEMENT_ID NUMBER NOT NULL,
  UNLOCKED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_USER_ACHIEVEMENT PRIMARY KEY (USER_ID, ACHIEVEMENT_ID),
  CONSTRAINT FK_UA_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER (ID),
  CONSTRAINT FK_UA_ACH  FOREIGN KEY (ACHIEVEMENT_ID) REFERENCES ACHIEVEMENT (ID)
);
